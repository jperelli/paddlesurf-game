// Tiny i18n: UI strings are written in English in the code and looked up here by that English text.
// Spanish is picked when the browser (or ?lang=es) asks for it; anything missing falls back to English.

export type Lang = 'en' | 'es';

function detect(): Lang {
  const forced = new URLSearchParams(location.search).get('lang');
  if (forced === 'es' || forced === 'en') return forced;
  const langs = navigator.languages?.length ? navigator.languages : [navigator.language];
  for (const l of langs) {
    const base = l.toLowerCase().split('-')[0];
    if (base === 'es') return 'es';
    if (base === 'en') return 'en';
  }
  return 'en';
}

